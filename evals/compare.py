"""Model-comparison harness.

Runs the golden suite once per model and prints a pass-rate table you can
paste into the README. Same scorer as the CI gate; only the model varies.

Usage:
    MODEL_API_KEY=… uv run python -m evals.compare \\
        google-gla:gemini-2.5-flash \\
        google-gla:gemini-2.5-flash-lite

Each `provider:model` argument uses the same MODEL_API_KEY (rotate keys
between invocations if providers differ). The script writes the table to
evals/model-comparison.md and prints it to stdout.
"""

from __future__ import annotations

import asyncio
import os
import sys
import time
from collections import defaultdict

from curb_worker.gateway import ModelChoice, build_model

from evals.conftest import EVAL_ROOT
from evals.runner import EvalResult, load_golden, run_one

OUT_PATH = EVAL_ROOT / "model-comparison.md"
INTER_CASE_DELAY_S = float(os.getenv("CURB_EVAL_DELAY_S", "4"))


async def _run_one_model(qualified: str, api_key: str) -> list[EvalResult]:
    cases = load_golden(EVAL_ROOT / "golden")
    model = build_model(ModelChoice(qualified=qualified, api_key=api_key))
    results: list[EvalResult] = []
    for i, case in enumerate(cases):
        if i > 0:
            await asyncio.sleep(INTER_CASE_DELAY_S)
        results.append(await run_one(case, agent_model=model))
    return results


def _render_table(per_model: dict[str, list[EvalResult]]) -> str:
    header = (
        "| Model | Pass rate | Verified | Conclusive | Inconclusive | Avg conf |\n"
        "| --- | --- | --- | --- | --- | --- |\n"
    )
    rows = []
    for model, results in per_model.items():
        inconclusive = sum(1 for r in results if r.error is not None)
        conclusive = len(results) - inconclusive
        verified = sum(1 for r in results if r.verified)
        rate = verified / conclusive if conclusive else 0.0
        confs = [r.confidence for r in results if r.verified]
        conf = sum(confs) / len(confs) if confs else 0.0
        rows.append(
            f"| `{model}` | **{rate * 100:.0f}%** | {verified} | "
            f"{conclusive} | {inconclusive} | {conf:.2f} |"
        )
    return header + "\n".join(rows) + "\n"


def _render_per_case(per_model: dict[str, list[EvalResult]]) -> str:
    """A second table: rows are cases, columns are models. Cell = verified Y/N."""
    case_ids: list[str] = []
    case_results: defaultdict[str, dict[str, EvalResult]] = defaultdict(dict)
    for model, results in per_model.items():
        for r in results:
            if r.case_id not in case_ids:
                case_ids.append(r.case_id)
            case_results[r.case_id][model] = r
    models = list(per_model.keys())
    header = "| Case | " + " | ".join(f"`{m}`" for m in models) + " |\n"
    sep = "| --- | " + " | ".join("---" for _ in models) + " |\n"
    rows = []
    for case_id in case_ids:
        cells = []
        for m in models:
            r = case_results[case_id].get(m)
            if r is None:
                cells.append("—")
            elif r.error:
                cells.append("⚠️ inconclusive")
            elif r.verified:
                cells.append(f"✅ ({r.confidence:.2f})")
            else:
                cells.append("❌")
        rows.append(f"| {case_id} | " + " | ".join(cells) + " |")
    return header + sep + "\n".join(rows) + "\n"


async def main() -> None:
    min_args = 2
    if len(sys.argv) < min_args:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    qualified_models = sys.argv[1:]
    api_key = os.environ.get("MODEL_API_KEY", "")
    if not api_key:
        print("MODEL_API_KEY must be set in the environment.", file=sys.stderr)
        sys.exit(2)

    per_model: dict[str, list[EvalResult]] = {}
    for q in qualified_models:
        print(f"[compare] running {q} …", flush=True)
        t0 = time.time()
        per_model[q] = await _run_one_model(q, api_key)
        print(f"[compare] {q} done in {time.time() - t0:.1f}s", flush=True)

    summary = _render_table(per_model)
    detail = _render_per_case(per_model)
    out = (
        "## Model comparison\n\n"
        f"_Generated by `uv run python -m evals.compare`, dataset: `evals/golden/` "
        f"({len(load_golden(EVAL_ROOT / 'golden'))} cases). Primary metric: "
        f"re-run-axe pass rate over conclusive cases._\n\n"
        + summary
        + "\n### Per-case detail\n\n"
        + detail
    )
    OUT_PATH.write_text(out)
    print(out)
    print(f"\nWritten to {OUT_PATH}")


if __name__ == "__main__":
    asyncio.run(main())
